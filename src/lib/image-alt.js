/** Consistent, descriptive alt text for marketing images (SEO + accessibility). */

export function integrationLogoAlt(platformName) {
  return `${platformName} integration logo`;
}

export function gomoStudioLogoAlt(variant) {
  return `GOMO Studio ${variant} logo`;
}

export function testimonialPhotoAlt(name, title) {
  return `Profile photo of ${name}, ${title}`;
}

export function blogCoverAlt(title) {
  return `Cover image for the blog article: ${title}`;
}

export function heroBackgroundAlt() {
  return "Soft lime and ink gradient background for the GOMO Studio hero section";
}
